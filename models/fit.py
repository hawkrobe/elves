def _circ_dist(a, b):
    """Circular distance in [0, 360)."""
    d = np.abs(a - b)
    return np.minimum(d, 360 - d)


def _next_nearest_angle_from_geometry(nearest_deg, target_deg):
    """
    Next-nearest trained angle = the closer of the two ±45° neighbors of nearest (mod 360).
    Reconstruct from geometry; do not use jsPsych/CSV next_nearest_angle.
    """
    nearest = np.asarray(nearest_deg, dtype=float)
    target = np.asarray(target_deg, dtype=float)
    n_plus = (nearest + 45) % 360
    n_minus = (nearest - 45 + 360) % 360
    d_plus = _circ_dist(target, n_plus)
    d_minus = _circ_dist(target, n_minus)
    return np.where(d_plus < d_minus, n_plus, n_minus)


def load_data():
    """Load and preprocess Experiment 1 data."""
    data_dir = Path(__file__).parent.parent / "data" / "full-production" / "processed_data"

    production = pd.read_csv(data_dir / "production.csv")
    participants = pd.read_csv(data_dir / "participants.csv")

    df = production.merge(
        participants[["subject_id", "time_pressure", "frequency_ratio"]],
        on="subject_id"
    )
    df["time_pressure"] = pd.to_numeric(df["time_pressure"], errors="coerce")
    df = df.dropna(subset=["time_pressure"])

    # Reconstruct next-nearest from geometry (nearest ±45°; whichever is closer to target). Do not use CSV column.
    df["nextNearestAngle"] = _next_nearest_angle_from_geometry(
        df["nearestAngle"].values, df["targetAngle"].values
    )

    # Compute distance to nearest LF trained angle
    df["dist_to_lf_deg"] = np.where(
        df["nearestFreq"] == "LF",
        np.abs(df["distance"]),
        _circ_dist(df["targetAngle"].values, df["nextNearestAngle"].values)
    )

    # Convert to model's theta space (0.5 = LF prototype, 0/1 = HF prototypes)
    df["theta"] = 0.5 - df["dist_to_lf_deg"] / 90

    # Filter to critical trials
    df = df[df["between_freqs"]]              # Between-frequency trials only
    df = df[df["timed_out"] == 0]              # Exclude timeouts
    df = df[(df["rt"] > 200) &                 # Exclude very fast responses
            (df["rt"] < df["time_pressure"] * 1000)]  # Exclude responses after deadline

    df["is_lf"] = (df["responseFreq"] == "LF").astype(int)

    return df



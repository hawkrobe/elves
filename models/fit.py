"""
RSA Race Model Fitting

Fits the race model to Experiment 1 data (2x2 design: time pressure × frequency ratio).

Model: A(w, t) = B(w) + δ · M(θ, w) · t

Parameters:
  - Shared across conditions: σ (semantic width), δ (drift rate), λ (lapse)
  - Varies by frequency ratio: B_HF (baseline advantage for HF words)
  - Varies by condition: T (effective processing time)

Usage:
    From repository root:  python models/fit.py
    From models/ directory (data path still uses repo root):  python fit.py

Data:
    Expects data/full-production/processed_data/production.csv and participants.csv
    (generated by analysis/cogsci2026/00_clean_data.R from raw_data/run-1).
    Next-nearest angle is reconstructed from geometry (nearest ±45°; whichever is closer to target),
    not from the jsPsych/CSV next_nearest_angle column.

Output:
    - race_model_data_exp1.csv: Trial-level data used for fit (for R so plots use same data as Python)
    - Fitted parameters and fit statistics printed to console
    - race_model_fit.png: Model fit visualization
    - fitted_params.npz, fitted_params_exp1.csv: Saved parameters
    - race_model_predictions_exp1.csv, race_model_schematic_data.csv, race_model_schematic_params.csv
    - race_model_P_LF_P_HF_vs_time_exp1_LF_prototype.csv (and optional .png/.pdf)
"""


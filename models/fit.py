def plot_fit(df, params, out_dir=None):
    """
    Plot P(LF) vs distance from LF: binned raw data + fitted race model curves.

    Two panels (frequency ratio 1:2 and 1:4); within each, two curves (5s vs 10s).
    Saves race_model_fit.png and race_model_fit.pdf to out_dir (default: models/).
    """
    if out_dir is None:
        out_dir = Path(__file__).parent
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    n_bins = 9
    dist_lo, dist_hi = 0.0, 45.0
    dist_grid = np.linspace(0.5, 44.5, 200)

    # Binned raw data: mean and SE of is_lf by condition and distance bin
    df_plot = df.copy()
    df_plot["dist_bin"] = pd.cut(
        df_plot["dist_to_lf_deg"],
        bins=np.linspace(dist_lo, dist_hi, n_bins + 1),
        include_lowest=True,
    )
    binned = (
        df_plot.groupby(["frequency_ratio", "time_pressure", "dist_bin"], observed=True)
        .agg(
            dist_mean=("dist_to_lf_deg", "mean"),
            p_lf=("is_lf", "mean"),
            n=("is_lf", "count"),
        )
        .reset_index()
    )
    binned["p_lf_se"] = np.sqrt(binned["p_lf"] * (1 - binned["p_lf"]) / binned["n"])

    # Model curves: P(LF) on fine grid for each of 4 conditions (δ fixed to 1)
    sigma = params["sigma"]
    lapse = params["lapse"]
    theta_grid = 0.5 - dist_grid / 90.0

    def curve_p_lf(B_hf, T):
        probs = _race_model_vec(
            jnp.array(theta_grid),
            sigma,
            jnp.full(len(theta_grid), B_hf),
            1.0,
            jnp.full(len(theta_grid), T),
            lapse,
        )
        return np.array(probs[:, 1])

    curves = {}
    T_by_cond = {
        ("1:2", 5): "T_12_5", ("1:2", 10): "T_12_10",
        ("1:4", 5): "T_14_5", ("1:4", 10): "T_14_10",
    }
    for fr, B_hf in [("1:2", params["B_hf_12"]), ("1:4", params["B_hf_14"])]:
        for tp in [5, 10]:
            T_val = params[T_by_cond[(fr, tp)]]
            curves[(fr, tp)] = curve_p_lf(B_hf, T_val)

    # Colors to match paper (strict 5s = red, lenient 10s = blue)
    colors_tp = {5: "#E94F37", 10: "#2E86AB"}

    fig, axes = plt.subplots(1, 2, figsize=(10, 4.5), sharey=True)
    for ax, fr in zip(axes, ["1:2", "1:4"]):
        for tp in [5, 10]:
            sub = binned[(binned["frequency_ratio"] == fr) & (binned["time_pressure"] == tp)]
            ax.errorbar(
                sub["dist_mean"],
                sub["p_lf"],
                yerr=sub["p_lf_se"],
                fmt="o",
                color=colors_tp[tp],
                capsize=3,
                label=f"{'Strict (5s)' if tp == 5 else 'Lenient (10s)'}",
            )
            ax.plot(
                dist_grid,
                curves[(fr, tp)],
                color=colors_tp[tp],
                linewidth=1.5,
            )
        ax.axvline(22.5, color="gray", linestyle="--", linewidth=1)
        ax.set_xlim(0, 45)
        ax.set_ylim(0, 1)
        ax.set_xlabel("Distance from LF (deg)")
        ax.set_ylabel("P(LF)" if ax == axes[0] else "")
        ax.set_title(f"Frequency ratio {fr}")
        ax.legend(loc="upper right", framealpha=0.9)
        ax.set_xticks(np.arange(0, 46, 10))
        ax.set_yticks(np.arange(0, 1.25, 0.25))
        ax.grid(True, alpha=0.3)
    plt.tight_layout()

    for ext in ["png", "pdf"]:
        out_path = out_dir / f"race_model_fit.{ext}"
        fig.savefig(out_path, bbox_inches="tight", dpi=300 if ext == "png" else None)
        print(f"Saved {out_path}")
    plt.close(fig)

    # Export prediction grid for R/ggplot (tidy: dist_to_lf, frequency_ratio, time_pressure, p_lf)
    pred_rows = []
    for fr in ["1:2", "1:4"]:
        for tp in [5, 10]:
            p_lf = curves[(fr, tp)]
            for d, p in zip(dist_grid, p_lf):
                pred_rows.append({"dist_to_lf": d, "frequency_ratio": fr, "time_pressure": tp, "p_lf": p})
    pd.DataFrame(pred_rows).to_csv(out_dir / "race_model_predictions_exp1.csv", index=False)
    print(f"Saved {out_dir / 'race_model_predictions_exp1.csv'}")



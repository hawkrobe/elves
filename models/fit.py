def plot_race_schematic(params, out_dir=None, theta=0.5, suffix=""):
    """
    Plot activation vs time at a given θ: HF vs LF baseline at t=0 and slopes (δ·M(θ,w)).
    Uses fitted σ, B_HF; δ=1. Saves race_model_schematic[suffix].png/pdf and CSVs for R/ggplot.

    theta: 0.5 = LF prototype (LF slope >> HF slope); 0.25 = boundary (LF slope = HF slope).
    suffix: e.g. "_boundary" for boundary figure filename.
    """
    if out_dir is None:
        out_dir = Path(__file__).parent
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    sigma = params["sigma"]
    delta = 1.0
    word_locs = [0.0, 0.5, 1.0]  # HF1, LF, HF2
    # At boundary (θ=0.25), nearest HF is at 0: M(0.25,0) = M(0.25,0.5) by symmetry
    M_hf = float(scipy_norm.pdf(theta, word_locs[0], sigma))
    M_lf = float(scipy_norm.pdf(theta, word_locs[1], sigma))
    slope_hf = delta * M_hf
    slope_lf = delta * M_lf

    t_max = 6.0
    t_vals = np.linspace(0, t_max, 200)

    # Colors to match paper
    color_hf = "#7B7B7B"
    color_lf = "#2E86AB"
    color_t5 = "#E94F37"
    color_t10 = "#2E86AB"

    fig, axes = plt.subplots(1, 2, figsize=(8, 4), sharey=True)
    for ax, (fr, B_hf, T_5, T_10) in zip(
        axes,
        [
            ("1:2", params["B_hf_12"], params["T_12_5"], params["T_12_10"]),
            ("1:4", params["B_hf_14"], params["T_14_5"], params["T_14_10"]),
        ],
    ):
        # A(HF, t) = B_HF + slope_hf * t; A(LF, t) = 0 + slope_lf * t
        A_hf = B_hf + slope_hf * t_vals
        A_lf = 0 + slope_lf * t_vals
        ax.plot(t_vals, A_hf, color=color_hf, lw=2, label=f"HF (B = {B_hf:.2f})")
        ax.plot(t_vals, A_lf, color=color_lf, lw=2, label=f"LF (B = 0)")
        ax.axhline(B_hf, color=color_hf, ls=":", alpha=0.6)
        ax.axhline(0, color=color_lf, ls=":", alpha=0.6)
        ax.axvline(T_5, color=color_t5, ls="--", lw=1.5, alpha=0.8)
        ax.axvline(T_10, color=color_t10, ls="--", lw=1.5, alpha=0.8)
        ax.set_xlim(0, t_max)
        ax.set_xlabel("Time (effective units)")
        ax.set_ylabel("Activation" if ax == axes[0] else "")
        ax.set_title(f"Frequency ratio {fr}")
        ax.legend(loc="upper left", frameon=True, fontsize=8)
        ax.grid(True, alpha=0.3)
        # Annotate slopes and position
        theta_label = "θ = 0.5 (LF prototype)" if theta == 0.5 else "θ = 0.25 (boundary)"
        ax.text(0.98, 0.02, f"{theta_label}\nslope HF = {slope_hf:.3f}\nslope LF = {slope_lf:.3f}",
                transform=ax.transAxes, fontsize=7, va="bottom", ha="right",
                bbox=dict(boxstyle="round", facecolor="wheat", alpha=0.5))
    plt.tight_layout()

    base = f"race_model_schematic{suffix}"
    for ext in ["png", "pdf"]:
        out_path = out_dir / f"{base}.{ext}"
        fig.savefig(out_path, bbox_inches="tight", dpi=300 if ext == "png" else None)
        print(f"Saved {out_path}")
    plt.close(fig)

    # Export schematic data for R/ggplot (only for default prototype run to avoid overwriting)
    if suffix == "":
        schematic_data = []
        for fr, B_hf in [("1:2", params["B_hf_12"]), ("1:4", params["B_hf_14"])]:
            for word, baseline, slope in [
                ("HF", B_hf, slope_hf),
                ("LF", 0.0, slope_lf),
            ]:
                for t in np.linspace(0, t_max, 50):
                    schematic_data.append({
                        "frequency_ratio": fr,
                        "word": word,
                        "baseline": baseline,
                        "slope": slope,
                        "t": t,
                        "activation": baseline + slope * t,
                    })
        pd.DataFrame(schematic_data).to_csv(out_dir / "race_model_schematic_data.csv", index=False)
        summary = []
        for fr, B_hf in [("1:2", params["B_hf_12"]), ("1:4", params["B_hf_14"])]:
            summary.append({"frequency_ratio": fr, "word": "HF", "baseline": B_hf, "slope": slope_hf})
            summary.append({"frequency_ratio": fr, "word": "LF", "baseline": 0.0, "slope": slope_lf})
        pd.DataFrame(summary).to_csv(out_dir / "race_model_schematic_params.csv", index=False)
        print(f"Saved {out_dir / 'race_model_schematic_data.csv'} and race_model_schematic_params.csv")


# =============================================================================
# P(LF) and P(HF) as a function of decision time (T)
# =============================================================================

def plot_P_LF_P_HF_vs_time_exp1(params, out_dir=None, theta=0.5, theta_label=None, suffix=""):
    """
    Plot P(LF) and P(HF) on the same axes as a function of effective decision time T.

    Shows how producers shift from HF to LF (or vice versa) as T increases.
    Uses fitted σ, B_HF per FR; at a fixed θ. Two panels (FR 1:2, FR 1:4).
    Exports CSV for R/ggplot (experiment1_race_model.qmd plot #3).

    At θ=0.5 (LF prototype), M(θ, LF) is maximal and LF can beat HF as T increases.
    """
    if out_dir is None:
        out_dir = Path(__file__).parent
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    if theta_label is None:
        theta_label = f"θ = {theta}" + (" (LF prototype)" if theta == 0.5 else " (boundary)" if theta == 0.25 else "")

    sigma = params["sigma"]
    lapse = params["lapse"]
    T_grid = np.linspace(0, 5.0, 300)
    theta_vec = jnp.full(len(T_grid), theta)

    color_lf = "#2980B9"
    color_hf = "#7B7B7B"
    color_t5 = "#D4A017"
    color_t10 = "#9C27B0"

    fig, axes = plt.subplots(1, 2, figsize=(10, 5), sharex=True, sharey=True)

    for i_col, fr in enumerate(["1:2", "1:4"]):
        ax = axes[i_col]
        B_hf = params["B_hf_12"] if fr == "1:2" else params["B_hf_14"]
        probs = _race_model_vec(
            theta_vec,
            sigma,
            jnp.full(len(T_grid), B_hf),
            1.0,
            jnp.array(T_grid),
            lapse,
        )
        probs = np.array(probs)
        p_lf = probs[:, 1]
        p_hf = probs[:, 0] + probs[:, 2]

        ax.plot(T_grid, p_lf, color=color_lf, linewidth=1.5, label="P(LF)")
        ax.plot(T_grid, p_hf, color=color_hf, linewidth=1.5, label="P(HF)")

        T_5 = params["T_12_5"] if fr == "1:2" else params["T_14_5"]
        T_10 = params["T_12_10"] if fr == "1:2" else params["T_14_10"]
        if T_5 <= T_grid.max():
            idx5 = np.argmin(np.abs(T_grid - T_5))
            ax.axvline(T_5, color=color_t5, ls="--", lw=1.2, alpha=0.8, label="Strict (5s)")
            ax.plot(T_5, p_lf[idx5], "o", color=color_lf, markersize=6)
            ax.plot(T_5, p_hf[idx5], "o", color=color_hf, markersize=6)
        if T_10 <= T_grid.max():
            idx10 = np.argmin(np.abs(T_grid - T_10))
            ax.axvline(T_10, color=color_t10, ls="--", lw=1.2, alpha=0.8, label="Lenient (10s)")
            ax.plot(T_10, p_lf[idx10], "o", color=color_lf, markersize=6)
            ax.plot(T_10, p_hf[idx10], "o", color=color_hf, markersize=6)

        ax.set_xlim(T_grid.min(), T_grid.max())
        ax.set_ylim(0, 1)
        ax.set_xlabel("Effective decision time T")
        ax.set_ylabel("P(LF) / P(HF)" if i_col == 0 else "")
        ax.set_title(f"FR {fr}")
        ax.legend(loc="center right", frameon=True, fontsize=8)
        ax.grid(True, alpha=0.3)
        ax.text(0.02, 0.98, theta_label, transform=ax.transAxes, fontsize=7, va="top", ha="left")

    plt.tight_layout()
    base = f"race_model_P_LF_P_HF_vs_time_exp1{suffix}"
    for ext in ["png", "pdf"]:
        out_path = out_dir / f"{base}.{ext}"
        fig.savefig(out_path, bbox_inches="tight", dpi=300 if ext == "png" else None)
        print(f"Saved {out_path}")
    plt.close(fig)

    # Export curve grid for R/ggplot: T, p_lf, p_hf per frequency_ratio (no payoff_structure in exp1)
    curve_rows = []
    for fr in ["1:2", "1:4"]:
        B_hf = params["B_hf_12"] if fr == "1:2" else params["B_hf_14"]
        probs = _race_model_vec(
            theta_vec,
            sigma,
            jnp.full(len(T_grid), B_hf),
            1.0,
            jnp.array(T_grid),
            lapse,
        )
        probs = np.array(probs)
        p_lf = probs[:, 1]
        p_hf = probs[:, 0] + probs[:, 2]
        for t, plf, phf in zip(T_grid, p_lf, p_hf):
            curve_rows.append({
                "frequency_ratio": fr, "T": t, "p_lf": plf, "p_hf": phf, "theta": theta,
            })
    out_csv = out_dir / f"race_model_P_LF_P_HF_vs_time_exp1{suffix}.csv"
    pd.DataFrame(curve_rows).to_csv(out_csv, index=False)
    print(f"Saved {out_csv}")


